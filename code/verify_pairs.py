"""Independently certify exceptional positivity using only one- and two-coin witnesses."""
from itertools import combinations
from math import gcd, lcm
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from verify_exceptional import CASES, fibonacci


class CertificateError(Exception):
    """Raised when any certificate check fails (independent of python -O)."""


def check(condition, message="certificate check failed"):
    if not condition:
        raise CertificateError(message)


def two_coin(n, a, b):
    """Is n in the nonnegative semigroup generated by a and b?"""
    g = gcd(a, b)
    if n % g:
        return False
    a, b, n = a // g, b // g, n // g
    if a == 1 or b == 1:
        return True
    x = (n * pow(a, -1, b)) % b
    return a * x <= n

def inspect(degrees, period, admitted):
    maximum = max(degrees)
    failures = []
    tested = 0
    required_two = 0
    for a in range(1, 2 * maximum - 2):
        if a % period not in admitted:
            continue
        targets = [fibonacci(a+d-1) for d in degrees]
        for size in range(1, len(degrees)+1):
            for subset in combinations(degrees, size):
                tested += 1
                coins = [fibonacci(d) for d in subset]
                hits = [t for t in targets if any(t % c == 0 for c in coins)]
                if len(hits) >= size:
                    continue
                required_two += 1
                count = sum(any(t % c == 0 for c in coins)
                            or any(two_coin(t,c,b) for c,b in combinations(coins,2))
                            for t in targets)
                if count < size:
                    failures.append((a, subset))
    return tested, required_two, failures

if __name__ == '__main__':
    for name, degrees, period, admitted in CASES:
        tested, two, failures = inspect(degrees, period, admitted)
        check(not failures, (name, failures))
        print(name, tested, two, "all passed")
